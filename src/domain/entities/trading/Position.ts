import { AppError } from "../../../shared/errors/AppError";
import { ErrorCodes } from "../../../shared/errors/ErrorCodes";
import { OrderSide, ProductType } from "./Order";

export { ProductType };

export const PositionSide = {
  LONG: "LONG",
  SHORT: "SHORT",
  CLOSED: "CLOSED",
} as const;
export type PositionSide = (typeof PositionSide)[keyof typeof PositionSide];

export interface PositionProps {
  id: string;
  userId: string;
  stockId: string;
  symbol: string;
  productType: ProductType;
  side?: PositionSide;
  quantity?: number;
  buyQty?: number;
  buyAmount?: number;
  sellQty?: number;
  sellAmount?: number;
  averagePrice?: number;
  realizedPnL?: number;
  blockedMargin?: number;
  createdAt?: Date;
  updatedAt?: Date;
}

export class Position {
  private constructor(
    private readonly props: {
      id: string;
      userId: string;
      stockId: string;
      symbol: string;
      productType: ProductType;
      side: PositionSide;
      quantity: number;
      buyQty: number;
      buyAmount: number;
      sellQty: number;
      sellAmount: number;
      averagePrice: number;
      realizedPnL: number;
      blockedMargin: number;
      createdAt: Date;
      updatedAt: Date;
    }
  ) {}

  static create(props: PositionProps): Position {
    if (!props.id || !props.userId || !props.stockId || !props.symbol) {
      throw new AppError(ErrorCodes.VALIDATION_FAILED);
    }

    return new Position({
      id: props.id,
      userId: props.userId,
      stockId: props.stockId,
      symbol: props.symbol.toUpperCase().trim(),
      productType: props.productType,
      side: props.side ?? PositionSide.CLOSED,
      quantity: props.quantity ?? 0,
      buyQty: props.buyQty ?? 0,
      buyAmount: props.buyAmount ?? 0,
      sellQty: props.sellQty ?? 0,
      sellAmount: props.sellAmount ?? 0,
      averagePrice: props.averagePrice ?? 0,
      realizedPnL: props.realizedPnL ?? 0,
      blockedMargin: props.blockedMargin ?? 0,
      createdAt: props.createdAt ?? new Date(),
      updatedAt: props.updatedAt ?? new Date(),
    });
  }

  // Getters
  get id(): string { return this.props.id; }
  get userId(): string { return this.props.userId; }
  get stockId(): string { return this.props.stockId; }
  get symbol(): string { return this.props.symbol; }
  get productType(): ProductType { return this.props.productType; }
  get side(): PositionSide { return this.props.side; }
  get quantity(): number { return this.props.quantity; }
  get buyQty(): number { return this.props.buyQty; }
  get buyAmount(): number { return this.props.buyAmount; }
  get sellQty(): number { return this.props.sellQty; }
  get sellAmount(): number { return this.props.sellAmount; }
  get averagePrice(): number { return this.props.averagePrice; }
  get realizedPnL(): number { return this.props.realizedPnL; }
  get blockedMargin(): number { return this.props.blockedMargin; }
  get createdAt(): Date { return this.props.createdAt; }
  get updatedAt(): Date { return this.props.updatedAt; }

  public isOpen(): boolean {
    return this.props.side !== PositionSide.CLOSED && this.props.quantity > 0;
  }

  public calculateUnrealizedPnL(currentLtp: number): number {
    if (!this.isOpen() || currentLtp <= 0) return 0;

    if (this.props.side === PositionSide.LONG) {
      return +((currentLtp - this.props.averagePrice) * this.props.quantity).toFixed(2);
    } else if (this.props.side === PositionSide.SHORT) {
      return +((this.props.averagePrice - currentLtp) * this.props.quantity).toFixed(2);
    }
    return 0;
  }

  public calculateTotalPnL(currentLtp: number): number {
    return +(this.props.realizedPnL + this.calculateUnrealizedPnL(currentLtp)).toFixed(2);
  }

  /**
   * Applies an executed order fill to this position.
   * Handles scaling-in (weighted avg price) and scaling-out / square-off (realized PnL).
   * Returns the incremental realized PnL generated by this fill.
   */
  public applyFill(side: OrderSide, fillQty: number, fillPrice: number): number {
    let incrementalPnL = 0;

    if (side === OrderSide.BUY) {
      this.props.buyQty += fillQty;
      this.props.buyAmount += +(fillQty * fillPrice).toFixed(2);

      if (this.props.side === PositionSide.SHORT) {
        // Covering a short position
        const closingQty = Math.min(this.props.quantity, fillQty);
        incrementalPnL = +((this.props.averagePrice - fillPrice) * closingQty).toFixed(2);
        this.props.realizedPnL += incrementalPnL;

        const remainingShort = this.props.quantity - closingQty;
        if (remainingShort > 0) {
          this.props.quantity = remainingShort;
        } else {
          // Short is completely covered
          const excessBuy = fillQty - closingQty;
          if (excessBuy > 0) {
            // Position flips to LONG
            this.props.side = PositionSide.LONG;
            this.props.quantity = excessBuy;
            this.props.averagePrice = fillPrice;
          } else {
            this.props.side = PositionSide.CLOSED;
            this.props.quantity = 0;
            this.props.averagePrice = 0;
          }
        }
      } else {
        // Adding to LONG (or opening new LONG from CLOSED)
        const totalCost = this.props.averagePrice * this.props.quantity + fillQty * fillPrice;
        this.props.quantity += fillQty;
        this.props.averagePrice = +(totalCost / this.props.quantity).toFixed(2);
        this.props.side = PositionSide.LONG;
      }
    } else if (side === OrderSide.SELL) {
      this.props.sellQty += fillQty;
      this.props.sellAmount += +(fillQty * fillPrice).toFixed(2);

      if (this.props.side === PositionSide.LONG) {
        // Closing a long position
        const closingQty = Math.min(this.props.quantity, fillQty);
        incrementalPnL = +((fillPrice - this.props.averagePrice) * closingQty).toFixed(2);
        this.props.realizedPnL += incrementalPnL;

        const remainingLong = this.props.quantity - closingQty;
        if (remainingLong > 0) {
          this.props.quantity = remainingLong;
        } else {
          // Long is completely sold
          const excessSell = fillQty - closingQty;
          if (excessSell > 0) {
            // Position flips to SHORT (only valid for MIS)
            this.props.side = PositionSide.SHORT;
            this.props.quantity = excessSell;
            this.props.averagePrice = fillPrice;
          } else {
            this.props.side = PositionSide.CLOSED;
            this.props.quantity = 0;
            this.props.averagePrice = 0;
          }
        }
      } else {
        // Adding to SHORT (or opening new SHORT from CLOSED)
        const totalCost = this.props.averagePrice * this.props.quantity + fillQty * fillPrice;
        this.props.quantity += fillQty;
        this.props.averagePrice = +(totalCost / this.props.quantity).toFixed(2);
        this.props.side = PositionSide.SHORT;
      }
    }

    this.props.updatedAt = new Date();
    return incrementalPnL;
  }

  public updateBlockedMargin(amount: number): void {
    this.props.blockedMargin = Math.max(0, amount);
    this.props.updatedAt = new Date();
  }
}
